# Cvičení 1 – For versus while
# Ke každému zadání si za pomlčku dopiš for, nebo while, a proč sis ho
# vybrala. Ptej se sama sebe: vím dopředu, kolikrát se to má zopakovat?

# 1)  Zatluč do prkna 10 hřebíků. - for, mám předem daný počet
# 2)  Buš kladivem do hřebíku, dokud není úplně zatlučený. - while, nevím kolikrát zatluču
# 3)  Zahřívej vodu, dokud se nezačne vařit. - while, nevíme jak dlouho
# 4)  Házej mincí, dokud nepadne panna. - while, nevím kdy padne panna
# 5)  Házej kostkou, dokud šestka nepadne potřetí. - while, nevím jak dlouho budu házet
# 6)  Zeptej se uživatelky na číslo a tolikrát hoď kostkou. for, až se zeptám na číslo, tolikrát hodím
# 7)  Hoď kostkou a vypiš, co padlo. for, hážu jen 1x - žádný
# 8)  Vypiš sudá čísla od 0 do 100. for, mám dopředu daná čísla, jen vypisuji sudá
# 9)  Vypiš sudá čísla od 0 do čísla, které zadá uživatelka. for - počet zadá uživatelka
# 10) Vypiš každé písmeno slova "Praha". - for, mám dané slovo Praha
# 11) Přidávej do košíku jablka, dokud košík neváží aspoň 2 kg. - while, nevím, jak dlouho budu přidávat jablka
# 12) Projdi 30 odpovědí v testu a spočítej, kolik jich je správně. - for, projdu 30 testů
